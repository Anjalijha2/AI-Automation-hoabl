// scripts/scaffold-poms.js
// Generates skeleton Page Object Model files from locators/<portal>/locator-map.json.
// Skips POMs that already exist (does not overwrite hand-written ones).
//
// Output: automation-repository/pages/<portal>/<Module>Page.js
//
// Run:  node scripts/scaffold-poms.js                     (all 4 portals)
//       node scripts/scaffold-poms.js --portal=sm
//       node scripts/scaffold-poms.js --portal=admin --force   (overwrite)

'use strict';
const fs   = require('fs');
const path = require('path');

const ROOT       = path.join(__dirname, '..');
const LOCATORS   = path.join(ROOT, 'locators');
const POM_BASE   = path.join(ROOT, 'automation-repository', 'pages');

// ─── Portal → folder mapping ─────────────────────────────────────────────────

