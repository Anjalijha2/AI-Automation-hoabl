// scripts/send-execution-report.js
// Mails the latest sprint Execution Report (HTML + XLSX attachments) via SMTP.
//
// SMTP creds via .env:
//   SMTP_HOST  (default smtp.office365.com)
//   SMTP_PORT  (default 587)
//   SMTP_USER  (auth user, often = SMTP_FROM)
//   SMTP_PASS  (account password / app password)
//   SMTP_FROM  (From: header)
//   SMTP_SECURE  optional 'true' for implicit TLS (465). Else STARTTLS on 587.
//   SMTP_IGNORE_TLS optional 'true' for plain SMTP (e.g. mailpit/maildev :1025).
//
// Recipient is hard-defaulted to the project owner; override with REPORT_TO.
//
// Usage:
//   node scripts/send-execution-report.js [--sprint 5] [--env UAT]
//   SMTP_HOST=localhost SMTP_PORT=1025 SMTP_IGNORE_TLS=true node scripts/send-execution-report.js

'use strict';

const fs   = require('fs');
const path = require('path');
require('dotenv').config();

const argv = process.argv.slice(2);
function arg(flag, def) {
  const i = argv.indexOf(flag);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : def;
}

const SPRINT  = arg('--sprint', '5');
const ENVNAME = arg('--env', 'UAT');
const ROOT    = path.resolve(__dirname, '..');
const DIR     = path.join(ROOT, 'manual-qa-repository', '06-test-runs', ENVNAME, `sprint-${SPRINT}`);
const HTML    = path.join(DIR, 'execution-report.html');
const XLSX    = path.join(DIR, 'execution-report.xlsx');

const TO      = process.env.REPORT_TO || 'anjali.jha@openspaceservices.com';
const FROM    = process.env.SMTP_FROM || process.env.SMTP_USER || 'qa-bot@xrportal.local';

if (!fs.existsSync(HTML) || !fs.existsSync(XLSX)) {
  console.error('[send-report] missing report files. Run `npm run report:exec` first.');
  console.error('  expected:', HTML);
  console.error('  expected:', XLSX);
  process.exit(1);
}

// Lazy-require nodemailer so a missing install gives a friendly error.
let nodemailer;
try { nodemailer = require('nodemailer'); }
catch (e) {
  console.error('[send-report] nodemailer not installed. Run: npm i -D nodemailer');
  process.exit(1);
}

const host = process.env.SMTP_HOST || 'smtp.office365.com';
const port = Number(process.env.SMTP_PORT || 587);
const secure = String(process.env.SMTP_SECURE || '').toLowerCase() === 'true';
const ignoreTLS = String(process.env.SMTP_IGNORE_TLS || '').toLowerCase() === 'true';

const transportOpts = {
  host,
  port,
  secure,           // true = implicit TLS (465); false = STARTTLS on 587
  ignoreTLS,        // dev-only — plain SMTP (mailpit/maildev :1025)
  requireTLS: !ignoreTLS && !secure,
  auth: (process.env.SMTP_USER && process.env.SMTP_PASS)
    ? { user: process.env.SMTP_USER, pass: process.env.SMTP_PASS }
    : undefined,
  tls: { ciphers: 'TLSv1.2' },
};

// Body summary: derive headline counts from the HTML report (cheap, no re-parse of XLSX)
const html = fs.readFileSync(HTML, 'utf8');
const summaryBlock = (html.match(/<table style="border-collapse:collapse;font-size:13px;">([\s\S]*?)<\/table>/) || [, ''])[1];
const date = new Date().toISOString().slice(0, 10);
const subject = `XR Portal QA — Sprint ${SPRINT} Execution Report — ${date}`;

const bodyHtml = `
<div style="font-family:'Segoe UI',Arial,sans-serif;color:#222;">
  <div style="background:#1F3864;color:#fff;padding:14px 22px;border-radius:6px 6px 0 0;">
    <div style="font-size:18px;font-weight:700;">XR Portal QA — Sprint ${SPRINT} (${ENVNAME})</div>
    <div style="font-size:12px;opacity:.9;">Execution Report · ${date}</div>
  </div>
  <div style="border:1px solid #ddd;border-top:0;padding:16px 22px;border-radius:0 0 6px 6px;">
    <p style="margin:0 0 10px;">The latest Test Case Execution Report is attached (HTML + XLSX).</p>
    <table style="border-collapse:collapse;font-size:13px;margin:8px 0;">${summaryBlock}</table>
    <p style="margin:14px 0 0;font-size:12px;color:#666;">
      Auto-generated by <code>scripts/send-execution-report.js</code>.
      The HTML attachment is the full mailable report; the XLSX mirror is archival.
    </p>
  </div>
</div>`;

(async () => {
  const transport = nodemailer.createTransport(transportOpts);
  console.log(`[send-report] SMTP ${host}:${port} secure=${secure} ignoreTLS=${ignoreTLS}`);
  try { await transport.verify(); console.log('[send-report] SMTP verified.'); }
  catch (e) { console.warn('[send-report] verify failed (will try send anyway):', e.message); }

  const info = await transport.sendMail({
    from: FROM,
    to:   TO,
    subject,
    html: bodyHtml,
    attachments: [
      { filename: `execution-report-sprint-${SPRINT}.html`, path: HTML, contentType: 'text/html' },
      { filename: `execution-report-sprint-${SPRINT}.xlsx`, path: XLSX,
        contentType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' },
    ],
  });

  console.log(`[send-report] sent: messageId=${info.messageId}`);
  if (info.accepted?.length) console.log('  accepted:', info.accepted.join(', '));
  if (info.rejected?.length) console.log('  rejected:', info.rejected.join(', '));
})().catch(e => {
  console.error('[send-report] FAILED:', e.message);
  process.exit(2);
});
